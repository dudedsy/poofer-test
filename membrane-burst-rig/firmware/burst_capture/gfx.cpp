void Gfx::clear() { memset(fb, 0, sizeof fb); }

void Gfx::pixel(int x, int y, bool on) {
  if (x < 0 || x >= GFX_W || y < 0 || y >= GFX_H) return;
  uint8_t &b = fb[(y >> 3) * GFX_W + x];
  uint8_t m = 1u << (y & 7);
  if (on) b |= m; else b &= ~m;
}

void Gfx::hline(int x0, int x1, int y) { for (int x = x0; x <= x1; x++) pixel(x, y, true); }

void Gfx::fill(int x, int y, int w, int h, bool on) {
  for (int j = y; j < y + h; j++) for (int i = x; i < x + w; i++) pixel(i, j, on);
}

void Gfx::invert(int x, int y, int w, int h) {
  for (int j = y; j < y + h; j++)
    for (int i = x; i < x + w; i++) {
      if (i < 0 || i >= GFX_W || j < 0 || j >= GFX_H) continue;
      fb[(j >> 3) * GFX_W + i] ^= 1u << (j & 7);
    }
}

int Gfx::text(int x, int y, const char *s, int scale) {
  for (; *s; s++) {
    unsigned char c = (unsigned char)*s;
    if (c < 0x20 || c > 0x7F) c = '?';
    const uint8_t *g = FONT[c - 0x20];
    for (int col = 0; col < 5; col++)
      for (int row = 0; row < 7; row++)
        if (g[col] & (1u << row))
          fill(x + col * scale, y + row * scale, scale, scale, true);
    x += 6 * scale;
  }
  return x;
}

int Gfx::width(const char *s, int scale) { return (int)strlen(s) * 6 * scale; }

void Gfx::text_right(int x_right, int y, const char *s, int scale) {
  text(x_right - width(s, scale) + scale, y, s, scale);
}
